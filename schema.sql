CREATE TABLE IF NOT EXISTS cars (
  id TEXT PRIMARY KEY,
  titel TEXT NOT NULL,
  preis REAL NOT NULL DEFAULT 0,
  km INTEGER NOT NULL DEFAULT 0,
  baujahr INTEGER NOT NULL DEFAULT 0,
  kraftstoff TEXT NOT NULL DEFAULT '---',
  getriebe TEXT NOT NULL DEFAULT '---',
  leistung INTEGER NOT NULL DEFAULT 0,
  hu TEXT NOT NULL DEFAULT '',
  beschreibung TEXT NOT NULL DEFAULT '',
  bilder TEXT NOT NULL DEFAULT '[]',
  erstelltAm TEXT NOT NULL DEFAULT ''
);
